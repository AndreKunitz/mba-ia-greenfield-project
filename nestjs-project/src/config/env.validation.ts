import * as Joi from 'joi';

export const envValidationSchema = Joi.object({
  NODE_ENV: Joi.string()
    .valid('development', 'production', 'test')
    .default('development'),
  PORT: Joi.number().port().default(3000),
  DB_HOST: Joi.string().default('localhost'),
  DB_PORT: Joi.number().default(5432),
  DB_USERNAME: Joi.string().required(),
  DB_PASSWORD: Joi.string().required(),
  DB_NAME: Joi.string().required(),
  JWT_SECRET: Joi.string().required(),
  JWT_REFRESH_SECRET: Joi.string().required(),
  JWT_ACCESS_EXPIRATION: Joi.string().default('15m'),
  JWT_REFRESH_EXPIRATION: Joi.string().default('7d'),
  CONFIRMATION_TOKEN_EXPIRATION_HOURS: Joi.number().default(1),
  PASSWORD_RESET_TOKEN_EXPIRATION_HOURS: Joi.number().default(1),
  APP_URL: Joi.string().uri().default('http://localhost:3000'),
  MAIL_HOST: Joi.string().default('mailpit'),
  MAIL_PORT: Joi.number().default(1025),
  MAIL_FROM: Joi.string().default('"StreamTube" <noreply@streamtube.com>'),
  SWAGGER_ENABLED: Joi.string().valid('true', 'false').default('false'),
  S3_ENDPOINT: Joi.string().uri().required(),
  S3_PUBLIC_ENDPOINT: Joi.string().uri().required(),
  S3_REGION: Joi.string().default('us-east-1'),
  S3_ACCESS_KEY: Joi.string().required(),
  S3_SECRET_KEY: Joi.string().required(),
  S3_BUCKET: Joi.string().required(),
  S3_FORCE_PATH_STYLE: Joi.string().valid('true', 'false').default('true'),
  S3_CORS_ALLOWED_ORIGINS: Joi.string().default('*'),
  REDIS_HOST: Joi.string().default('redis'),
  REDIS_PORT: Joi.number().port().default(6379),
  QUEUE_PREFIX: Joi.string().default('bull'),
  VIDEO_MAX_SIZE_BYTES: Joi.number().integer().min(1).default(10737418240),
  VIDEO_PART_SIZE_BYTES: Joi.number().integer().min(5242880).default(67108864),
  VIDEO_ALLOWED_CONTENT_TYPES: Joi.string().default(
    'video/mp4,video/webm,video/quicktime,video/x-matroska',
  ),
  VIDEO_UPLOAD_URL_TTL_SECONDS: Joi.number().integer().min(1).default(900),
  VIDEO_URL_TTL_SECONDS: Joi.number().integer().min(1).default(3600),
  VIDEO_JOB_ATTEMPTS: Joi.number().integer().min(1).default(3),
  VIDEO_JOB_BACKOFF_MS: Joi.number().integer().min(0).default(5000),
  VIDEO_RECONCILE_INTERVAL_SECONDS: Joi.number().integer().min(1).default(300),
  VIDEO_PROCESSING_STALE_SECONDS: Joi.number().integer().min(1).default(3600),
  VIDEO_UPLOAD_TTL_HOURS: Joi.number().integer().min(1).default(24),
});
